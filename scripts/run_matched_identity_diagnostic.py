#!/usr/bin/env python3
"""Post-lock fixed-C observed identity diagnostic matched to the frozen null.

Requires authorized private inputs. Does not refit primary outcome or
intervention models, change the tuned observed probes, or modify locked files.
"""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))

import pandas as pd
from run_phase3_audit import load_config, identity_probe_oof, with_folds, git_commit
from surgical_skill2.audit import classification_metrics
from surgical_skill2.corrected_inference import matched_permutation_p
from build_technical_corrections import digest, read, write, OUT


def main():
    config, config_hash = load_config()
    null_path = ROOT / 'results/predictions/private/phase3_identity_null.parquet'
    feature_path = ROOT / 'data/processed/private/phase2_features.csv'
    expected = next(r for r in read(ROOT / 'data/manifests/phase3_artifacts.csv')
                    if r['path'] == str(null_path.relative_to(ROOT)))
    if digest(null_path) != expected['sha256'] or config_hash != expected['config_sha256']:
        raise ValueError('Frozen null or configuration hash mismatch')
    if digest(feature_path) != '0c351007805f52f41459f622faa3c979f0b410685006763fbfcba1fc431a1e50':
        raise ValueError('Feature matrix differs from the verified frozen input')
    null = pd.read_parquet(null_path)
    fixed_c = float(config['permutations']['fixed_logistic_c'])
    if set(null.selected_hyperparameter) != {f'C={fixed_c:g}'} or set(null.model) != {'multinomial_logistic'}:
        raise ValueError('Null pipeline specification mismatch')
    if set(null.permutation_type) != {'record_wise'}:
        raise ValueError('Wrong permutation scheme')
    folded = with_folds(pd.read_csv(feature_path, na_values=['NA']), 'same_participant')
    outputs, predictions = [], []
    spec = dict(model='multinomial_logistic', C=fixed_c, selection='fixed',
                preprocessing='outer_train_median_standard_scale', folds='same_participant',
                endpoint='balanced_accuracy')
    for (dataset, task), group in folded.groupby(['dataset', 'task'], sort=True):
        observed_rows = identity_probe_oof(group.reset_index(drop=True), 'multinomial_logistic',
                                          config, config_hash, git_commit(), fixed_c=fixed_c)
        observed = pd.DataFrame(observed_rows)
        task_null = null.loc[(null.dataset == dataset) & (null.task == task)]
        observed_trials = set(zip(observed.trial_key, observed.test_fold))
        null_ba = []
        for permutation, shuffled in task_null.groupby('permutation'):
            if set(zip(shuffled.trial_key, shuffled.test_fold)) != observed_trials or len(shuffled) != len(observed):
                raise ValueError('Observed/null trial and fold mismatch')
            if sorted(shuffled.y_true.astype(str)) != sorted(observed.y_true.astype(str)):
                raise ValueError('Identity permutation did not preserve label counts')
            null_ba.append(classification_metrics(shuffled)['balanced_accuracy'])
        if len(null_ba) != 50:
            raise ValueError('Expected exactly 50 frozen permutations')
        accuracy = classification_metrics(observed)['balanced_accuracy']
        # Observed and null configurations are verified above and generated by
        # the identical archived identity_probe_oof routine, without tuning.
        p = matched_permutation_p(accuracy, null_ba, observed_spec=spec, null_spec=spec)
        outputs.append(dict(dataset=dataset, task=task, model='fixed_C_logistic', C=fixed_c,
                            balanced_accuracy=accuracy, null_median=float(pd.Series(null_ba).median()),
                            empirical_p_value=p, permutations=len(null_ba)))
        predictions.extend(observed_rows)
        print(f'{dataset}/{task}: fixed-C BA={accuracy:.6f}, unadjusted p={p:.6f}', flush=True)
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / 'identity_matched_null.csv'
    if path.exists():
        old = pd.read_csv(path)
        pd.testing.assert_frame_equal(old, pd.DataFrame(outputs), check_exact=False, atol=1e-12, rtol=0)
    write(path, outputs)
    private = ROOT / 'results/predictions/private/corrections_2026-11-16'
    private.mkdir(parents=True, exist_ok=True)
    prediction_path = private / 'identity_fixed_C_observed.parquet'
    pd.DataFrame(predictions).to_parquet(prediction_path, index=False)
    inputs = [feature_path, null_path, ROOT / 'data/folds/same_participant.csv',
              ROOT / 'configs/experiments/phase3_baseline.yaml',
              ROOT / 'scripts/run_phase3_audit.py', ROOT / 'src/surgical_skill2/audit.py',
              ROOT / 'src/surgical_skill2/corrected_inference.py', Path(__file__).resolve()]
    manifest = dict(date='2026-11-16', status='post-lock exploratory matched identity diagnostic',
                    pipeline=spec, generating_parent_commit=git_commit(),
                    inputs={str(p.relative_to(ROOT)): digest(p) for p in inputs},
                    outputs={str(p.relative_to(ROOT)): digest(p) for p in [path, prediction_path]})
    (OUT / 'matched_identity_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')


if __name__ == '__main__':
    main()
